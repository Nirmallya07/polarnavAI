export const riskColorScale = [
  { min: 0, max: 24, color: '#7ad7b1' },
  { min: 25, max: 49, color: '#b7d978' },
  { min: 50, max: 69, color: '#f7c76d' },
  { min: 70, max: 84, color: '#f39b5a' },
  { min: 85, max: 100, color: '#d95a5a' },
]

export const formatRiskColor = (score) => {
  const match = riskColorScale.find((entry) => score >= entry.min && score <= entry.max)
  return match ? match.color : '#d95a5a'
}
